#define NP_AXIS_MAX 16383
#define PI 3.14159265358979323846

int np_pose_fresh(np_freshness *f, unsigned data_id, unsigned long long now_ms)
{
    if (data_id != f->data_id) {
        f->data_id = data_id;
        f->changed_ms = now_ms;
    }
    return data_id != 0 && now_ms - f->changed_ms < NP_STALE_MS;
}

/* TrackIR's checksum over the pose record. */
static unsigned cksum(unsigned char buf[], unsigned size)
{
    int rounds = size >> 2;
    int rem = size % 4;
    int c = size;
    int a0, a2;

    if (size == 0 || buf == NULL)
        return 0;

    while (rounds != 0) {
        short lo, hi; /* memcpy: reading the record through a short pointer breaks strict aliasing */
        memcpy(&lo, buf, 2);
        memcpy(&hi, buf + 2, 2);
        a0 = lo;
        a2 = hi;
        buf += 4;
        c += a0;
        a2 ^= (c << 5);
        a2 <<= 11;
        c ^= a2;
        c += (c >> 11);
        --rounds;
    }
    switch (rem) {
    case 3:
        a0 = *(short int *)buf;
        a2 = *(signed char *)(buf + 2);
        c += a0;
        a2 = (a2 << 2) ^ c;
        c ^= (a2 << 16);
        a2 = (c >> 11);
        break;
    case 2:
        a2 = *(short int *)buf;
        c += a2;
        c ^= (c << 11);
        a2 = (c >> 17);
        break;
    case 1:
        a2 = *(signed char *)(buf);
        c += a2;
        c ^= (c << 10);
        a2 = (c >> 1);
        break;
    default:
        break;
    }
    if (rem != 0)
        c += a2;

    c ^= (c << 3);
    c += (c >> 5);
    c ^= (c << 4);
    c += (c >> 17);
    c ^= (c << 25);
    c += (c >> 6);

    return (unsigned)c;
}

/* Scramble the pose record with a game's key. */
static void scramble(unsigned char buf[], unsigned size, const unsigned char table[8])
{
    unsigned table_ptr = 0;
    unsigned char var = 0x88;
    unsigned char tmp;

    do {
        tmp = buf[--size];
        buf[size] = tmp ^ table[table_ptr] ^ var;
        var += size + tmp;
        if (++table_ptr >= 8)
            table_ptr = 0;
    } while (size != 0);
}

static float clamp_axis(double x)
{
    return (float)(x > NP_AXIS_MAX ? NP_AXIS_MAX : x < -NP_AXIS_MAX ? -NP_AXIS_MAX : x);
}


/* Angles of +-180 degrees and positions of +-500 mm span the axis. */
void np_fill_record(tir_data_t *d, const volatile FTData *pose, int fresh)
{
    if (!fresh) {
        d->status = NP_STATUS_DISABLED;
        d->yaw = d->pitch = d->roll = d->tx = d->ty = d->tz = 0;
        return;
    }
    d->status = NP_STATUS_OK;
    d->yaw = clamp_axis(pose->Yaw * NP_AXIS_MAX / PI);
    d->pitch = clamp_axis(pose->Pitch * NP_AXIS_MAX / PI);
    d->roll = clamp_axis(pose->Roll * NP_AXIS_MAX / PI);
    d->tx = clamp_axis(pose->X * NP_AXIS_MAX / 500.);
    d->ty = clamp_axis(pose->Y * NP_AXIS_MAX / 500.);
    d->tz = clamp_axis(pose->Z * NP_AXIS_MAX / 500.);
}

void np_seal_record(tir_data_t *d, const unsigned char *key)
{
    d->cksum = 0;
    d->cksum = cksum((unsigned char *)d, sizeof *d);
    if (key)
        scramble((unsigned char *)d, sizeof *d, key);
}

const unsigned char *np_game_key(unsigned short id, const char **name)
{
    for (size_t i = 0; i < sizeof scrambled_games / sizeof scrambled_games[0]; i++)
        if (scrambled_games[i].id == id) {
            if (name)
                *name = scrambled_games[i].name;
            return scrambled_games[i].key;
        }
    if (name)
        *name = NULL;
    return NULL;
}

